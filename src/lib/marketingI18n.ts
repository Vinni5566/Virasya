export function getMarketingI18n(language?: string): MarketingI18nStrings {
  if (!language) return MARKETING_I18N.English;
  const cleanLang = language.trim().toLowerCase();
  
  const foundKey = Object.keys(MARKETING_I18N).find(
    key => key.toLowerCase() === cleanLang
  );

  if (foundKey) {
    return MARKETING_I18N[foundKey];
  }

  return MARKETING_I18N.English;
}
